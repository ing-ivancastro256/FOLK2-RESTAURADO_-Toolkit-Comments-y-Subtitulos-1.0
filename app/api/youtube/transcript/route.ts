import { NextRequest, NextResponse } from 'next/server';
import {
  listLanguages,
  fetchTranscript,
  YoutubeTranscriptDisabledError,
  YoutubeTranscriptNotAvailableError,
  YoutubeTranscriptNotAvailableLanguageError,
  YoutubeTranscriptVideoUnavailableError,
  YoutubeTranscriptTooManyRequestError,
  YoutubeTranscriptInvalidVideoIdError,
} from 'youtube-transcript-plus';
import { AvailableCaptionTrack, TranscriptSegment, VideoTranscript } from '@/lib/types';

// Decodificación segura de entidades HTML para limpiar el texto
function decodeHtmlEntities(str: string): string {
  return str
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&#x27;/g, "'")
    .replace(/&nbsp;/g, ' ')
    .replace(/&#(\d+);/g, (_, dec) => String.fromCharCode(dec));
}

// Parser de XML nativo timedtext para fallbacks
function parseTimedTextXml(xmlText: string): TranscriptSegment[] {
  const segments: TranscriptSegment[] = [];
  const regex = /<text\s+start="([\d.]+)"(?:\s+dur="([\d.]+)")?[^>]*>([\s\S]*?)<\/text>/g;
  let match;

  while ((match = regex.exec(xmlText)) !== null) {
    const start = parseFloat(match[1]);
    const duration = match[2] ? parseFloat(match[2]) : 2;
    const text = decodeHtmlEntities(match[3]).replace(/<[^>]+>/g, '').replace(/[\r\n]+/g, ' ').trim();
    if (text) {
      segments.push({
        start: Number(start.toFixed(2)),
        duration: Number(duration.toFixed(2)),
        text,
      });
    }
  }

  return segments;
}

export async function GET(req: NextRequest) {
  const { searchParams } = new URL(req.url);
  const videoId = searchParams.get('videoId');
  const action = searchParams.get('action'); // 'languages' para consultar idiomas disponibles
  const lang = searchParams.get('lang') || undefined;

  // Validación estricta del ID de video
  if (!videoId || !/^[a-zA-Z0-9_-]{11}$/.test(videoId)) {
    return NextResponse.json(
      { error: 'ID de video de YouTube inválido o no proporcionado (debe ser de 11 caracteres).' },
      { status: 400 }
    );
  }

  // =========================================================================
  // OPERACIÓN A: Consultar idiomas y pistas de subtítulos disponibles
  // =========================================================================
  if (action === 'languages') {
    try {
      const rawTracks = await listLanguages(videoId);

      if (!rawTracks || rawTracks.length === 0) {
        return NextResponse.json(
          {
            error: 'Este video no tiene subtítulos ni transcripciones activadas por el creador.',
            hasNoCaptions: true,
            languages: [],
            totalResults: 0,
          },
          { status: 404 }
        );
      }

      // Normalizar estructura sin inventar información
      const languages: AvailableCaptionTrack[] = rawTracks.map((track) => ({
        languageCode: track.languageCode || 'unknown',
        languageName: track.languageName || track.languageCode || 'Idioma sin nombre',
        isAutoGenerated: Boolean(track.isAutoGenerated),
        isTranslatable: (track as any).isTranslatable ?? true,
      }));

      return NextResponse.json({
        videoId,
        totalResults: languages.length,
        languages,
      });
    } catch (err: unknown) {
      if (err instanceof YoutubeTranscriptDisabledError) {
        return NextResponse.json(
          {
            error: 'Los subtítulos están deshabilitados por el creador en este video.',
            hasNoCaptions: true,
            disabled: true,
            languages: [],
          },
          { status: 404 }
        );
      }

      if (err instanceof YoutubeTranscriptNotAvailableError) {
        return NextResponse.json(
          {
            error: 'No hay transcripciones disponibles para este video en YouTube.',
            hasNoCaptions: true,
            languages: [],
          },
          { status: 404 }
        );
      }

      if (err instanceof YoutubeTranscriptVideoUnavailableError) {
        return NextResponse.json(
          {
            error: 'El video no está disponible (puede ser privado, eliminado o restringido por edad/región).',
            unavailable: true,
            languages: [],
          },
          { status: 404 }
        );
      }

      if (err instanceof YoutubeTranscriptTooManyRequestError) {
        return NextResponse.json(
          {
            error: 'YouTube está limitando temporalmente las solicitudes automatizadas. Intenta de nuevo en unos instantes.',
            rateLimited: true,
            languages: [],
          },
          { status: 429 }
        );
      }

      if (err instanceof YoutubeTranscriptInvalidVideoIdError) {
        return NextResponse.json(
          { error: 'ID de video de YouTube inválido.' },
          { status: 400 }
        );
      }

      const errorObj = err as Error;
      return NextResponse.json(
        {
          error: `Error al consultar idiomas de subtítulos: ${errorObj.message || 'Error desconocido'}`,
          languages: [],
        },
        { status: 500 }
      );
    }
  }

  // =========================================================================
  // OPERACIÓN B: Extraer transcripción completa para el idioma seleccionado
  // =========================================================================
  try {
    // 1. Extraer mediante youtube-transcript-plus
    const rawSegments = await fetchTranscript(videoId, {
      lang: lang || undefined,
    });

    if (!rawSegments || rawSegments.length === 0) {
      return NextResponse.json(
        {
          error: 'No se encontraron segmentos de texto en la transcripción de este video.',
          hasNoCaptions: true,
        },
        { status: 404 }
      );
    }

    // Normalizar segmentos con marcas de tiempo en segundos
    const segments: TranscriptSegment[] = rawSegments.map((s) => ({
      start: Number(s.offset.toFixed(2)),
      duration: Number(s.duration.toFixed(2)),
      text: decodeHtmlEntities(s.text).replace(/[\r\n]+/g, ' ').trim(),
    })).filter((s) => Boolean(s.text));

    if (segments.length === 0) {
      return NextResponse.json(
        {
          error: 'La transcripción extraída no contiene texto válido.',
          hasNoCaptions: true,
        },
        { status: 404 }
      );
    }

    const fullText = segments.map((s) => s.text).join(' ');

    const transcriptData: VideoTranscript = {
      videoId,
      language: lang || (rawSegments[0] as any).lang || 'es',
      languageName: lang ? lang.toUpperCase() : 'Predeterminado',
      isAutoGenerated: false,
      segments,
      fullText,
      createdAt: Date.now(),
    };

    return NextResponse.json(transcriptData);
  } catch (err: unknown) {
    // Manejo de errores específicos tipados por la librería
    if (err instanceof YoutubeTranscriptDisabledError) {
      return NextResponse.json(
        {
          error: 'Los subtítulos y transcripciones han sido deshabilitados por el creador en este video.',
          hasNoCaptions: true,
          disabled: true,
        },
        { status: 404 }
      );
    }

    if (err instanceof YoutubeTranscriptNotAvailableLanguageError) {
      return NextResponse.json(
        {
          error: `El idioma seleccionado "${lang}" no está disponible para este video.`,
          notAvailableLang: true,
          availableLanguages: (err as any).availableLangs || [],
        },
        { status: 404 }
      );
    }

    if (err instanceof YoutubeTranscriptNotAvailableError) {
      // Intento de fallback secundario con endpoint directo de timedtext antes de claudicar
      const fallbackLangs = lang ? [lang, 'es', 'en'] : ['es', 'en'];
      for (const fl of fallbackLangs) {
        try {
          const directUrl = `https://video.google.com/timedtext?v=${videoId}&lang=${fl}`;
          const directRes = await fetch(directUrl, { signal: AbortSignal.timeout(3000) });
          if (directRes.ok) {
            const xml = await directRes.text();
            if (xml && xml.includes('<text')) {
              const parsed = parseTimedTextXml(xml);
              if (parsed.length > 0) {
                return NextResponse.json({
                  videoId,
                  language: fl,
                  languageName: fl.startsWith('es') ? 'Español' : fl.toUpperCase(),
                  isAutoGenerated: false,
                  segments: parsed,
                  fullText: parsed.map((p) => p.text).join(' '),
                  createdAt: Date.now(),
                } as VideoTranscript);
              }
            }
          }
        } catch {
          // Continuar al error estándar
        }
      }

      return NextResponse.json(
        {
          error: 'No se encontraron subtítulos ni transcripción disponible para este video en YouTube.',
          hasNoCaptions: true,
        },
        { status: 404 }
      );
    }

    if (err instanceof YoutubeTranscriptVideoUnavailableError) {
      return NextResponse.json(
        {
          error: 'El video no está disponible (puede ser privado, eliminado o restringido por YouTube).',
          unavailable: true,
        },
        { status: 404 }
      );
    }

    if (err instanceof YoutubeTranscriptTooManyRequestError) {
      return NextResponse.json(
        {
          error:
            'YouTube ha detectado un volumen alto de solicitudes automatizadas. Por favor espera unos momentos y vuelve a intentarlo.',
          rateLimited: true,
        },
        { status: 429 }
      );
    }

    const errorObj = err as Error;
    return NextResponse.json(
      {
        error: `Error al extraer la transcripción: ${errorObj.message || 'Error desconocido'}`,
      },
      { status: 500 }
    );
  }
}
